const { test } = require('node:test');
const assert = require('node:assert/strict');
const R = require('../js/report.js');
const C = require('../js/chart.js');
const fs = require('node:fs');
const path = require('node:path');

const item = { question: 'Revenue by region', sql: 'SELECT region, SUM(total) AS revenue FROM orders GROUP BY region', tables: ['orders', 'customers'], mode: 'demo', answer: 'Top: South.', assumptions: ['a1'], result: { columns: ['region', 'revenue'], rows: [['South', 9998.17], ['East|West', 3979.99]] }, chart: { type: 'bar', x: 'region', y: 'revenue' } };
test('share links hold only question, SQL, table names and chart type, and round-trip unicode', () => {
  const secretish = Object.assign({}, item, { key: 'sk-test-NOT-REAL', apiKey: 'x', result: { columns: ['email'], rows: [['avery@mail.example']] }, question: 'Umsatz für Région ✓' });
  const link = R.shareLink('https://shaikbasha1437.github.io/askdata-ai/#old', secretish);
  assert.match(link, /^https:\/\/shaikbasha1437\.github\.io\/askdata-ai\/#share=[A-Za-z0-9_-]+$/);
  const decoded = R.b64urlDecode(link.split('#share=')[1]);
  assert.ok(!/sk-test|avery|mail\.example|apiKey|rows/.test(decoded));
  assert.deepEqual(Object.keys(JSON.parse(decoded)).sort(), ['d', 'q', 's', 'v']);
  const back = R.parseShare('#share=' + link.split('#share=')[1]);
  assert.equal(back.question, 'Umsatz für Région ✓'); assert.equal(back.sql, item.sql); assert.deepEqual(back.tables, ['orders', 'customers']);
  assert.equal(R.parseShare('#share=%%%'), null); assert.equal(R.parseShare('#nothing'), null);
});
test('Markdown report escapes pipes and includes answer, assumptions and SQL', () => {
  const md = R.markdown([item, { question: 'Delete it', abstain: 'Read-only.' }], { title: 'T', tables: ['orders'] });
  assert.match(md, /^# T/); assert.match(md, /\*\*Answer:\*\* Top: South\./); assert.match(md, /- a1/); assert.match(md, /```sql\nSELECT region/);
  assert.match(md, /\| East\\\|West \| \$3,979\.99 \|/); assert.match(md, /> Read-only\./);
});
test('HTML report is self-contained and escapes content', () => {
  const evil = Object.assign({}, item, { question: '<img src=x onerror=alert(1)>' });
  const html = R.html([evil], { title: 'R' }, (x) => C.render(x.chart, x.result.columns, x.result.rows, {}));
  assert.ok(!html.includes('<img src=x')); assert.match(html, /&lt;img src=x/); assert.match(html, /<svg[^>]+role="img"/); assert.ok(!/<script/i.test(html));
});
test('SQL and CSV files', () => {
  assert.match(R.sqlFile(item), /^-- Revenue by region\n-- Generated by AskData AI \(demo rules\)[\s\S]*GROUP BY region;\n$/);
  assert.equal(R.csv(item), 'region,revenue\r\nSouth,9998.17\r\nEast|West,3979.99\r\n');
  assert.equal(R.fileSafe('Top 5 / products?'), 'top-5-products');
});
test('chart picking: KPI, line for dates, bar for categories, pie respected, scatter for two numbers', () => {
  assert.equal(C.pick(['total'], [[5]], null).type, 'kpi');
  assert.equal(C.pick(['month', 'revenue'], [['2025-01', 1], ['2025-02', 2], ['2025-03', 3]], null).type, 'line');
  assert.equal(C.pick(['region', 'revenue'], [['A', 1], ['B', 2]], null).type, 'bar');
  assert.equal(C.pick(['status', 'n', 'pct'], [['A', 1, 50], ['B', 1, 50]], { type: 'pie' }).y, 'n');
  assert.equal(C.pick(['x', 'y'], [[1, 2], [3, 4], [5, 6]], null).type, 'scatter');
  assert.equal(C.pick(['k', 'v'], Array.from({ length: 30 }, (_, i) => ['k' + i, i]), { type: 'pie' }).type, 'bar');
  const s = C.pick(['month', 'plan', 'mrr'], [['2025-01', 'A', 1], ['2025-01', 'B', 2], ['2025-02', 'A', 3]], null);
  assert.equal(s.type, 'line'); assert.equal(s.series, 'plan');
});
test('SVG rendering for every chart type is well-formed and escapes labels', () => {
  const cols = ['label', 'value']; const rows = [['<b>A</b>', 10], ['B & C', 20], ['D', -5]];
  for (const type of ['bar', 'line', 'pie']) { const svg = C.render({ type, x: 'label', y: 'value' }, cols, rows, { title: 'T <x>' }); assert.match(svg, /^<svg[\s\S]*<\/svg>$/); assert.ok(!svg.includes('<b>A')); assert.match(svg, /&lt;b&gt;A/); }
  assert.match(C.render({ type: 'scatter', x: 'a', y: 'b' }, ['a', 'b'], [[1, 2], [2, 3]], {}), /<circle/);
  assert.equal(C.render({ type: 'kpi', y: 'v' }, ['v'], [[1]], {}), '');
  assert.match(C.render({ type: 'line', x: 'm', y: 'v', series: 's' }, ['m', 's', 'v'], [['2025-01', 'A', 1], ['2025-02', 'A', 2], ['2025-01', 'B', 3]], { dark: true }), /polyline[\s\S]*polyline/);
  assert.equal(C.fmt(1234.5, 'revenue'), '$1,234.50'); assert.equal(C.fmt(12, 'orders'), '12'); assert.equal(C.fmt(33.333, 'pct'), '33.3%'); assert.equal(C.fmt(null), '—');
});
test('service worker precaches files that exist and only caches pinned CDN versions', () => {
  const root = path.join(__dirname, '..');
  const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
  const files = JSON.parse(/const FILES = (\[[\s\S]*?\]);/.exec(sw)[1].replace(/'/g, '"'));
  for (const f of files) if (f !== './') assert.ok(fs.existsSync(path.join(root, f)), f + ' missing');
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  for (const m of html.matchAll(/src="\.\/([^"]+)"/g)) assert.ok(files.includes('./' + m[1]), m[1] + ' not precached');
  const re = new RegExp(/const CDN_RE = (\/.*\/i);/.exec(sw)[1].slice(1, -2), 'i');
  assert.ok(re.test('https://cdn.jsdelivr.net/npm/@duckdb/duckdb-wasm@1.33.1-dev57.0/dist/duckdb-eh.wasm'));
  assert.ok(re.test('https://cdn.jsdelivr.net/npm/apache-arrow@17.0.0/+esm'));
  assert.ok(!re.test('https://cdn.jsdelivr.net/npm/@duckdb/duckdb-wasm@latest/+esm'));
  assert.ok(!re.test('https://api.openai.com/v1/chat/completions'));
  assert.match(sw, /const VERSION = 'askdata-v\d+'/);
});
test('engine module: identical table shape for both dialects, literal quoting', () => {
  const E = require('../js/engine.js');
  const t = { name: 'o', columns: [{ name: 'a', type: 'INTEGER' }, { name: 'b', type: 'DATE' }, { name: 'c"q', type: 'TEXT' }] };
  assert.equal(E.createSql('duckdb', t), 'CREATE TABLE "o" ("a" BIGINT, "b" DATE, "c""q" VARCHAR)');
  assert.equal(E.createSql('sqlite', t), 'CREATE TABLE "o" ("a" INTEGER, "b" TEXT, "c""q" TEXT)');
  assert.equal(E.lit("O'Brien"), "'O''Brien'"); assert.equal(E.lit(null), 'NULL'); assert.equal(E.lit(NaN), 'NULL');
});
